import type { PositioningData, TemplateMode } from './types.js';
import {
  assemblePositioningStatement,
  assembleSixtySecondStatement,
  assembleOnlynessStatement,
  assembleBrandPromise,
  assembleVoiceStatement,
  assembleVillainStatement,
  assembleAntiPositioning,
  getTemplateSections,
} from './frameworks.js';

function hasValue(s: string): boolean {
  return s.trim().length > 0;
}

function buildFullTemplate(d: PositioningData): string {
  const lines: string[] = [];

  lines.push(`# Brand Positioning: ${d.identity.brandName}`);
  lines.push('');

  lines.push('## Positioning Statement');
  lines.push(assemblePositioningStatement(d));
  lines.push('');

  if (hasValue(d.sixtySecond.outcome)) {
    lines.push('## 60-Second Positioning');
    lines.push(assembleSixtySecondStatement(d));
    lines.push('');
  }

  if (hasValue(d.onlyness.category)) {
    lines.push('## Onlyness Statement');
    lines.push(assembleOnlynessStatement(d));
    lines.push('');
  }

  if (hasValue(d.brandPromise.promise)) {
    lines.push('## Brand Promise + Proof');
    lines.push(`**Promise:** ${assembleBrandPromise(d)}`);
    lines.push('');
    lines.push('**Proof Architecture:**');
    if (hasValue(d.brandPromise.processProof))
      lines.push(`- **Process:** ${d.brandPromise.processProof}`);
    if (hasValue(d.brandPromise.outcomeProof))
      lines.push(`- **Outcomes:** ${d.brandPromise.outcomeProof}`);
    if (hasValue(d.brandPromise.transparencyProof))
      lines.push(`- **Transparency:** ${d.brandPromise.transparencyProof}`);
    lines.push('');
  }

  if (hasValue(d.voice.personalityTrait)) {
    lines.push('## Voice Definition');
    lines.push(assembleVoiceStatement(d));
    lines.push('');
    lines.push('**Guidelines:**');
    if (hasValue(d.voice.bannedWords)) {
      lines.push(`- **Don't:** ${d.voice.bannedWords}`);
    }
    lines.push('');
  }

  if (hasValue(d.heavenHell.hellFunctional)) {
    lines.push('## Heaven vs Hell');
    lines.push('');
    lines.push('### Where they are now (Hell)');
    if (hasValue(d.heavenHell.hellFunctional))
      lines.push(`- **Functional:** ${d.heavenHell.hellFunctional}`);
    if (hasValue(d.heavenHell.hellEmotional))
      lines.push(`- **Emotional:** ${d.heavenHell.hellEmotional}`);
    if (hasValue(d.heavenHell.hellSocial))
      lines.push(`- **Social:** ${d.heavenHell.hellSocial}`);
    lines.push('');
    lines.push('### Where they want to be (Heaven)');
    if (hasValue(d.heavenHell.heavenFunctional))
      lines.push(`- **Functional:** ${d.heavenHell.heavenFunctional}`);
    if (hasValue(d.heavenHell.heavenEmotional))
      lines.push(`- **Emotional:** ${d.heavenHell.heavenEmotional}`);
    if (hasValue(d.heavenHell.heavenSocial))
      lines.push(`- **Social:** ${d.heavenHell.heavenSocial}`);
    lines.push('');
    lines.push('### The Bridge');
    lines.push(
      `We help them go from ${d.heavenHell.hellFunctional} to ${d.heavenHell.heavenFunctional} through ${d.sixtySecond.uniqueMethod || 'our unique approach'}.`,
    );
    lines.push('');
  }

  if (hasValue(d.villain.villain)) {
    lines.push('## The Villain');
    lines.push(assembleVillainStatement(d));
    lines.push('');
  }

  if (hasValue(d.antiPositioning.notFor)) {
    lines.push('## Anti-Positioning');
    lines.push(assembleAntiPositioning(d));
    lines.push('');
  }

  lines.push('---');
  lines.push(
    '*Generated by position-cli · Based on the Stand The F\\*ck Out methodology*',
  );

  return lines.join('\n');
}

function buildPitchTemplate(d: PositioningData): string {
  const sections = getTemplateSections('pitch');
  const lines: string[] = [];

  lines.push(`# ${d.identity.brandName} — Positioning Pitch`);
  lines.push('');

  if (sections.includes('positioning')) {
    lines.push('## Positioning Statement');
    lines.push(assemblePositioningStatement(d));
    lines.push('');
  }

  if (sections.includes('onlyness') && hasValue(d.onlyness.category)) {
    lines.push('## Onlyness Statement');
    lines.push(assembleOnlynessStatement(d));
    lines.push('');
  }

  if (sections.includes('promise') && hasValue(d.brandPromise.promise)) {
    lines.push('## Brand Promise');
    lines.push(assembleBrandPromise(d));
    lines.push('');
  }

  lines.push('---');
  lines.push(
    '*Generated by position-cli · Based on the Stand The F\\*ck Out methodology*',
  );

  return lines.join('\n');
}

function buildOnePagerTemplate(d: PositioningData): string {
  const sections = getTemplateSections('one-pager');
  const lines: string[] = [];

  lines.push(`# ${d.identity.brandName} — One Pager`);
  lines.push('');

  if (sections.includes('positioning')) {
    lines.push('## Positioning');
    lines.push(assemblePositioningStatement(d));
    lines.push('');
  }

  if (sections.includes('onlyness') && hasValue(d.onlyness.category)) {
    lines.push('## Onlyness');
    lines.push(assembleOnlynessStatement(d));
    lines.push('');
  }

  if (sections.includes('villain') && hasValue(d.villain.villain)) {
    lines.push('## The Villain');
    lines.push(assembleVillainStatement(d));
    lines.push('');
  }

  if (
    sections.includes('anti-positioning') &&
    hasValue(d.antiPositioning.notFor)
  ) {
    lines.push('## Anti-Positioning');
    lines.push(assembleAntiPositioning(d));
    lines.push('');
  }

  lines.push('---');
  lines.push(
    '*Generated by position-cli · Based on the Stand The F\\*ck Out methodology*',
  );

  return lines.join('\n');
}

export function buildTemplate(
  data: PositioningData,
  mode: TemplateMode,
): string {
  switch (mode) {
    case 'pitch':
      return buildPitchTemplate(data);
    case 'one-pager':
      return buildOnePagerTemplate(data);
    case 'full':
    default:
      return buildFullTemplate(data);
  }
}
